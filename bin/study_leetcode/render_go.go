package main

import (
	"fmt"
	"os"
	"strings"
)

func textToGoComments(text string) string {
	lines := strings.Split(strings.TrimSpace(text), "\n")
	var b strings.Builder
	for _, line := range lines {
		if line == "" {
			b.WriteString("//\n")
			continue
		}
		b.WriteString("// ")
		b.WriteString(line)
		b.WriteByte('\n')
	}
	return b.String()
}

func renderDailyGo(set practiceSet, fetchedAt string) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by study_leetcode; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// DAILY LEETCODE — %s\n", todayDate())
	if fetchedAt != "" {
		fmt.Fprintf(&b, "// Fetched: %s\n", fetchedAt)
	}
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// RUN:      go run ./drills/leetcode/daily.go\n")
	fmt.Fprintf(&b, "// Refresh:  go run . -- --run leetcode -- --refresh\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "package main\n\n")
	fmt.Fprintf(&b, "import \"fmt\"\n\n")

	for i, p := range set.problems {
		dailyMark := ""
		if p.Daily {
			dailyMark = " · daily challenge"
		}
		fmt.Fprintf(&b, "// ━━━ %d. %s (#%d) — %s%s ━━━\n", i+1, p.Title, p.Num, p.Diff, dailyMark)
		fmt.Fprintf(&b, "// %s\n", lcURL(p.Slug))
		fmt.Fprintf(&b, "//\n\n")
	}
	// Tags and reflex links name the pattern; they go last, as answers.
	b.WriteString("// ━━━ ANSWERS (check after naming each pattern) ━━━\n")
	for i, p := range set.problems {
		line := fmt.Sprintf("// %d. %s — %s", i+1, p.Slug, orNone(p.Pattern))
		if p.ReflexFn != "" {
			line += " · reflex " + p.ReflexFn
		}
		b.WriteString(line + "\n")
	}
	b.WriteString("\n")

	b.WriteString("func main() {\n")
	fmt.Fprintf(&b, "\tfmt.Println(\"Daily LeetCode — %s\")\n", todayDate())
	fmt.Fprintf(&b, "\tfmt.Println(\"%d problems — click links below.\")\n", len(set.problems))
	b.WriteString("\tfmt.Println()\n")
	for i, p := range set.problems {
		dailyMark := ""
		if p.Daily {
			dailyMark = " [daily]"
		}
		fmt.Fprintf(&b, "\tfmt.Printf(\"%%2d. #%%d %%s (%%s)%%s\\n\", %d, %d, %q, %q, %q)\n",
			i+1, p.Num, p.Title, p.Diff, dailyMark)
		fmt.Fprintf(&b, "\tfmt.Println(%q)\n", lcURL(p.Slug))
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func dailyGoIsCurrent(path string) bool {
	data, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	header := "// DAILY LEETCODE — " + todayDate()
	return strings.Contains(string(data), header)
}

func writeDailyGo(repoRoot string, set practiceSet, fetchedAt string, refresh bool) error {
	path := dailyGoPath(repoRoot)
	if !refresh && dailyGoIsCurrent(path) {
		return nil
	}
	body, err := renderDailyGo(set, fetchedAt)
	if err != nil {
		return err
	}
	return os.WriteFile(path, []byte(body), 0o644)
}
